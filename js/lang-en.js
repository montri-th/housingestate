const bold = (one, many) => (el, t) => t.plural(el.querySelector('strong')?.textContent, one, many);
/** A district written with its word (เขต in Bangkok, อำเภอ elsewhere): the area index's English, else the name. */
const district = (t, name) => t.known(`อำเภอ${name}`) || t.known(`เขต${name}`) || t.known(name) || t.part(name);

